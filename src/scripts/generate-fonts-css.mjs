/**
 * Writes resources/css/fonts.css from the installed @fontsource packages (core#557).
 *
 * The site serves the families the theme settings offer (ThemeSettingsDTO) itself, latin and latin-ext only.
 * The per-subset stylesheets of @fontsource carry no unicode-range, so two of them for one weight would hide
 * each other: the ranges are read from the package's full stylesheet instead.
 *
 * Usage: npm run fonts:css (after adding a family here, to package.json and to ThemeSettingsDTO).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** @type {Array<[family: string, slug: string]>} */
const FAMILIES = [
    ['Inter', 'inter'],
    ['Poppins', 'poppins'],
    ['Montserrat', 'montserrat'],
    ['Roboto', 'roboto'],
    ['Open Sans', 'open-sans'],
    ['Playfair Display', 'playfair-display'],
];
const WEIGHTS = [400, 500, 600, 700];
// latin-ext first: for a character both cover, the face declared last wins, and that must be latin
const SUBSETS = ['latin-ext', 'latin'];

/**
 * @param {string} slug
 * @param {string} subset
 * @returns {string}
 */
function unicodeRange(slug, subset) {
    const css = readFileSync(resolve(root, `node_modules/@fontsource/${slug}/400.css`), 'utf8');
    const block = css
        .split('@font-face')
        .find((part) => part.includes(`${slug}-${subset}-400-normal.woff2`));
    const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (range === undefined) {
        throw new Error(`No unicode-range for ${slug} (${subset})`);
    }

    return range;
}

let css = `/*
 * The fonts the theme settings offer, served by the site itself (core#557): no request to a font service.
 * Latin and latin-ext only; the browser downloads a file when a page uses that family, weight and range.
 * Generated by scripts/generate-fonts-css.mjs (npm run fonts:css): do not edit by hand.
 */
`;

for (const [family, slug] of FAMILIES) {
    for (const weight of WEIGHTS) {
        for (const subset of SUBSETS) {
            const file = `${slug}-${subset}-${weight}-normal.woff2`;
            readFileSync(resolve(root, `node_modules/@fontsource/${slug}/files/${file}`));
            css += `
@font-face {
    font-family: '${family}';
    font-style: normal;
    font-display: swap;
    font-weight: ${weight};
    src: url('../../node_modules/@fontsource/${slug}/files/${file}') format('woff2');
    unicode-range: ${unicodeRange(slug, subset)};
}
`;
        }
    }
}

writeFileSync(resolve(root, 'resources/css/fonts.css'), css);
