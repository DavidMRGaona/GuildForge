#!/usr/bin/env node
// Type report of the core's public frontend API: the declarations vue-tsc emits
// for the public entries of resources/js/public-api.json and for every core file
// those declarations import, plus the hand-written resources/js/types/**/*.d.ts
// that module tsconfigs include, in one reviewable file. A change to it is a change
// to what modules compile against, so CI fails until the report is regenerated
// (`npm run public-api:report`) and the change shows up in the pull request.
//
//   node scripts/public-api-report.mjs          compare with the report
//   node scripts/public-api-report.mjs --write  regenerate the report
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPublicApi } from './public-api.mjs';

const srcDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const jsDir = resolve(srcDir, 'resources/js');
const reportPath = resolve(jsDir, 'public-api.api.md');
// Inside node_modules, so the types of tsconfig.json (vite/client, node) resolve as they do for it
const workDir = resolve(srcDir, 'node_modules/.cache/public-api-report');
const outDir = join(workDir, 'dts');
const api = readPublicApi(srcDir);

function emitDeclarations() {
    rmSync(workDir, { recursive: true, force: true });
    mkdirSync(workDir, { recursive: true });
    const tsconfig = join(workDir, 'tsconfig.json');
    writeFileSync(
        tsconfig,
        JSON.stringify({
            extends: resolve(srcDir, 'tsconfig.json'),
            compilerOptions: {
                noEmit: false,
                declaration: true,
                emitDeclarationOnly: true,
                removeComments: true,
                rootDir: jsDir,
                outDir,
            },
            files: Object.values(api.entries).map((entry) => resolve(srcDir, entry)),
            include: [],
        })
    );
    const vueTsc = createRequire(import.meta.url).resolve('vue-tsc/bin/vue-tsc.js');
    const result = spawnSync(process.execPath, [vueTsc, '-p', tsconfig], { stdio: 'inherit' });
    if (result.status !== 0) {
        console.error('vue-tsc failed: the public API does not type-check.');
        process.exit(1);
    }
}

/** The emitted declaration of a core file, from an `@/` or relative import in a declaration. */
function declarationOf(specifier, fromFile) {
    let base;
    if (specifier.startsWith('@/')) base = join(outDir, specifier.slice(2));
    else if (specifier.startsWith('.')) base = resolve(dirname(fromFile), specifier);
    else return null;
    base = base.replace(/\.(ts|js)$/, '');
    for (const candidate of [`${base}.d.ts`, `${base}/index.d.ts`]) {
        if (existsSync(candidate)) return candidate;
    }
    return null;
}

/** The declarations of the public entries and of the core files they import, path => content. */
function collectReport() {
    const pending = Object.values(api.entries).map((entry) =>
        join(outDir, relative(jsDir, resolve(srcDir, entry)).replace(/\.ts$/, '') + '.d.ts')
    );
    const files = new Map();
    while (pending.length > 0) {
        const file = pending.pop();
        if (files.has(file)) continue;
        const content = readFileSync(file, 'utf8');
        files.set(file, content);
        for (const match of content.matchAll(/(?:from\s+|import\()["']([^"']+)["']/g)) {
            const imported = declarationOf(match[1], file);
            if (imported !== null) pending.push(imported);
        }
    }
    const emitted = [...files.keys()].map((file) => {
        const path = relative(outDir, file).replace(/\.d\.ts$/, '');
        return [path.endsWith('.vue') ? path : `${path}.ts`, files.get(file)];
    });
    // Hand-written declarations (PageProps, env) emit nothing, and module tsconfigs include them
    const handWritten = readdirSync(resolve(jsDir, 'types'), { recursive: true })
        .filter((file) => file.endsWith('.d.ts'))
        .map((file) => [`types/${file}`, readFileSync(resolve(jsDir, 'types', file), 'utf8')]);

    return [...emitted, ...handWritten].sort(([a], [b]) => (a < b ? -1 : 1));
}

function render(files) {
    const sections = files.map(
        ([path, content]) => `## resources/js/${path}\n\n\`\`\`ts\n${content.trim()}\n\`\`\`\n`
    );
    return (
        '# Public frontend API report\n\n' +
        'Generated by `npm run public-api:report` from resources/js/public-api.json: the declarations\n' +
        'of the public entries, of the core files they import and of resources/js/types/**/*.d.ts,\n' +
        'which module tsconfigs include. Do not edit it by hand.\n\n' +
        sections.join('\n')
    );
}

emitDeclarations();
const report = render(collectReport());

if (process.argv.includes('--write')) {
    writeFileSync(reportPath, report);
    console.log(`Wrote ${relative(srcDir, reportPath)}`);
    process.exit(0);
}

const expected = existsSync(reportPath) ? readFileSync(reportPath, 'utf8') : '';
if (report !== expected) {
    const generated = join(workDir, 'public-api.api.md');
    writeFileSync(generated, report);
    const diff = spawnSync(
        'git',
        ['diff', '--no-index', '--no-color', '--unified=1', reportPath, generated],
        { encoding: 'utf8' }
    );
    const lines = (diff.stdout ?? '').split('\n');
    console.error(lines.slice(0, 80).join('\n') + (lines.length > 80 ? '\n…' : ''));
    console.error(
        'The public API changed: review it and run npm run public-api:report ' +
            '(a removed or changed export is a breaking change for modules).'
    );
    process.exit(1);
}
console.log('Public API report up to date.');
